@register_function(
    aliases=["fetch_promoter_library", "启动子文库", "真实部件库",
             "组合启动子文库", "sigma70文库", "Urtecho"],
    category="synthetic_biology",
    description="下载一份**真实测量过的**组合式 σ70 启动子文库(Urtecho et al. 2019, GEO GSE108535):10,898 个变体,由 5 个序列元件(UP element / -35 / spacer / -10 / 基因组背景)组合而成,3×8×8×8×8=12,288 的全因子填满了 88.7%,每个变体都有实测 RNA 表达值和至少 4 条独立 barcode 重复。这是包里唯一一份**因子水平本身就是数据的一部分**的数据集 —— 所以 doe_design/analyse_doe/bayesian_optimize 可以在它上面做到闭环:提议的组合能直接回查实测值。`background` 是完美平衡的区组因子(每层 1536 个)。sequences=True 额外拉 8.9 MB,给出每个变体真实的 150 nt 序列。Fetch a real combinatorial sigma70 promoter library with measured expression.",
    examples=[
        "lib = ov.synbio.fetch_promoter_library()",
        "lib = ov.synbio.fetch_promoter_library(sequences=True)   # +8.9 MB, real DNA",
        "lib.groupby('minus35')['expression'].median().sort_values()",
    ],
    related=["synbio.doe_design", "synbio.analyse_doe",
             "synbio.bayesian_optimize", "synbio.promoter_library",
             "synbio.realise_design"],
    requires={},
    produces={},
)
def fetch_promoter_library(
    *,
    sequences: bool = False,
    log2: bool = True,
    cache_dir: Optional[str] = None,
    timeout: float = 180.0,
) -> "pd.DataFrame":
    """A real combinatorial promoter library, one row per variant.

    Urtecho et al. built σ70 promoters as every combination of three UP elements,
    eight −35 boxes, eight spacers, eight −10 boxes and eight genomic
    backgrounds, then measured RNA expression for all of them with a
    genomically-encoded multiplexed reporter assay.

    Parameters
    ----------
    sequences
        Also join the per-variant 150 nt sequence and the number of independent
        barcodes measured for it. Downloads a further 8.9 MB. Every one of the
        10,898 variants matches exactly one sequence, and each sequence is
        unambiguous across its barcodes — so this is a real orderable sequence
        per design point, not a reconstruction.
    log2
        Add a ``log2_expression`` column. Expression spans 143-fold across the
        library and its effects are multiplicative, so effect estimates and
        Gaussian-process surrogates both belong on a log scale.

    Returns
    -------
    pandas.DataFrame
        ``variant``, the five element columns of :data:`PROMOTER_ELEMENTS`,
        ``expression`` (RNA, arbitrary units), optionally ``log2_expression``,
        ``sequence`` and ``n_barcodes``.

    Notes
    -----
    What makes this dataset worth the download is that the factor levels *are*
    the data. A design over these five elements can be analysed, and the
    resulting recommendation can then be **looked up** among the measurements —
    so a design-build-test-learn loop closes on real numbers and the tutorial can
    report whether the recommendation was actually right. Pairing a design matrix
    with responses measured under some other condition produces effect estimates
    that are pure noise, and the numbers do not announce it.

    Reproduces the paper's central finding: −35 and −10 dominate (η² = 0.31 and
    0.22 of the variance in log2 expression, 9.1× and 6.9× between the best and
    worst level), while the UP element, spacer and background are minor terms
    (η² = 0.03, 0.04, 0.01).

    References
    ----------
    Urtecho G, Tripp AD, Insigne KD, Kim H, Kosuri S. *Biochemistry* 58,
    1539-1551 (2019). GEO accession GSE108535.
    """
    import numpy as np
    import pandas as pd

    root = _data_dir(cache_dir)
    local = _download(_VARIANTS_URL,
                      os.path.join(root, "GSE108535_sigma70_variant_data.txt.gz"),
                      timeout, "σ70 启动子文库表达数据")

    # whitespace-delimited despite the .txt extension; no field contains a space
    frame = pd.read_csv(local, compression="gzip", sep=r"\s+")
    missing = set(_COLUMN_RENAMES) - set(frame.columns)
    if missing:
        raise RuntimeError(
            f"下载到的 σ70 数据缺少预期列 {sorted(missing)},拿到的是 "
            f"{list(frame.columns)}。GEO 上的文件格式可能变了 —— "
            f"删掉缓存 {local} 重试,或按 GSE108535 的说明自行解析。")
    frame = frame.rename(columns=_COLUMN_RENAMES)
    frame = frame[["variant", *PROMOTER_ELEMENTS, "expression"]]

    if log2:
        frame["log2_expression"] = np.log2(frame["expression"].to_numpy(dtype=float))

    if sequences:
        mapping_local = _download(
            _MAPPING_URL,
            os.path.join(root, "GSE108535_barcode_mapping.txt.gz"),
            timeout, "σ70 文库的 barcode→序列映射(8.9 MB)")
        mapping = pd.read_csv(mapping_local, compression="gzip", sep=r"\s+")
        # The two files spell the UP-element token differently ('gourse-326fold-up'
        # against 'gourse_326fold_up'), and '->' in the mutation tokens also
        # contains a hyphen. Normalising every hyphen to an underscore in both is
        # consistent and joins 10898/10898.
        key = lambda s: s.str.replace("-", "_", regex=False)  # noqa: E731
        per_variant = (mapping.assign(_k=key(mapping["name"]))
                       .groupby("_k")
                       .agg(sequence=("most_common", "first"),
                            n_barcodes=("barcode", "size")))
        joined = frame.join(per_variant, on=key(frame["variant"]))
        unmatched = int(joined["sequence"].isna().sum())
        if unmatched:
            raise RuntimeError(
                f"{unmatched}/{len(frame)} 个变体没能匹配到序列。两个 GEO 文件的"
                f"命名约定可能变了,不做静默丢弃 —— 请核对 GSE108535 的 "
                f"barcode_mapping 与 variant_data 两个表。")
        frame = joined

    frame.attrs["source"] = "GEO GSE108535 (Urtecho et al. 2019, Biochemistry)"
    frame.attrs["response"] = "expression"
    frame.attrs["factors"] = list(PROMOTER_ELEMENTS)
    return frame.reset_index(drop=True)


_RYEGRASS_URL = ("https://raw.githubusercontent.com/cran/drc/master/data/"
                 "ryegrass.rda")


@register_function(
    aliases=["fetch_dose_response_dataset", "剂量反应数据", "真实剂量数据",
             "ryegrass", "示例剂量反应"],
    category="synthetic_biology",
    description="下载一份**真实测量的**剂量-反应数据(Streibig 的黑麦草实验:阿魏酸浓度对根长的抑制,7 个浓度水平、每级 3–6 个重复,随 R 的 drc 包发布)。用作 dose_response 的输入。它是抑制型响应且带真实重复,所以能看出重复内的散布 —— 用一条平滑的理论曲线演示拟合器,等于没有演示。Fetch a real measured dose-response dataset.",
    examples=[
        "data = ov.synbio.fetch_dose_response_dataset()",
        "fit = ov.synbio.dose_response(data['concentration'], data['response'])",
    ],
    related=["synbio.dose_response", "synbio.plot_dose_response",
             "synbio.fetch_growth_dataset"],
    requires={},
    produces={},
)
def fetch_dose_response_dataset(cache_dir: Optional[str] = None,
                                timeout: float = 60.0) -> "pd.DataFrame":
    """Root length against ferulic acid concentration, 24 measurements.

    The canonical dose-response teaching dataset (Streibig), distributed with the
    R package *drc*. Returned as ``concentration`` (µM) and ``response`` (root
    length, cm).

    Fitting it with a four-parameter log-logistic gives ED50 ≈ 3.0 µM, against
    the ≈ 3.06 µM *drc* reports for the same data — which is the point of using a
    published dataset rather than a curve drawn from the equation being fitted.
    """
    local = _download(_RYEGRASS_URL,
                      os.path.join(_data_dir(cache_dir), "ryegrass.rda"),
                      timeout, "剂量-反应示例数据(drc 的 ryegrass)")
    try:
        import pyreadr
    except ImportError as exc:
        raise ImportError(
            "这份数据是 R 的 .rda 格式,读取需要 pyreadr(pip install pyreadr)。"
        ) from exc
    frame = pyreadr.read_r(local)["ryegrass"]
    frame = frame.rename(columns={"conc": "concentration", "rootl": "response"})
    frame = frame[["concentration", "response"]].reset_index(drop=True)
    frame.attrs["source"] = "Streibig ryegrass assay, distributed with R/drc"
    frame.attrs["units"] = {"concentration": "µM ferulic acid",
                            "response": "root length (cm)"}
    return frame


