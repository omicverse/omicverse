r"""Real measured datasets, for when a demonstration needs data it did not invent.

Every function here downloads a **published measurement** and caches it. Nothing
is simulated. That distinction is the whole point: a design tool shown only on
data generated by its own assumptions has not been shown to work on anything.

* :func:`fetch_promoter_library` — 10,898 σ70 promoter variants built as a
  near-complete factorial over five sequence elements, with measured RNA
  expression (Urtecho et al. 2019).

The growth-curve dataset lives in :mod:`~omicverse.synbio._assay`
(:func:`~omicverse.synbio.fetch_growth_dataset`) and the *E. coli* protein
abundance table in :mod:`~omicverse.synbio._context`
(:func:`~omicverse.synbio.fetch_ecoli_abundance`).

**On the cache.** Files land in ``$OMICOS_SYNBIO_DATA_DIR`` if set, else
``$OMICOS_SYNBIO_GEM_DIR``, else ``~/.omicverse/synbio_data``. The default
variant table is 227 kB; ``sequences=True`` pulls a further 8.9 MB. On a cluster
with a small home quota, set the environment variable to scratch.
"""
from __future__ import annotations

import os
from typing import TYPE_CHECKING, Optional

from .._registry import register_function

if TYPE_CHECKING:  # pragma: no cover
    import pandas as pd


# GEO series GSE108535 — Urtecho, Tripp, Insigne, Kim & Kosuri (2019),
# "Systematic Dissection of Sequence Elements Controlling sigma70 Promoters Using
# a Genomically Encoded Multiplexed Reporter Assay in Escherichia coli",
# Biochemistry 58(11):1539-1551.  NCBI GEO is a public archive intended for
# programmatic access, which is why the data is taken from here rather than from
# the publisher's supplementary files.
_GEO = ("https://ftp.ncbi.nlm.nih.gov/geo/series/GSE108nnn/GSE108535/suppl/")
_VARIANTS_URL = _GEO + "GSE108535_sigma70_variant_data.txt.gz"
_MAPPING_URL = _GEO + "GSE108535_barcode_mapping.txt.gz"

#: The five sequence elements varied in the library, in promoter order.
PROMOTER_ELEMENTS = ("up_element", "minus35", "spacer", "minus10", "background")

_COLUMN_RENAMES = {
    "UP_element": "up_element",
    "Minus35": "minus35",
    "Spacer": "spacer",
    "Minus10": "minus10",
    "Background": "background",
    "RNA_exp_average": "expression",
    "name": "variant",
}


def _data_dir(cache_dir: Optional[str] = None) -> str:
    root = (cache_dir
            or os.environ.get("OMICOS_SYNBIO_DATA_DIR")
            or os.environ.get("OMICOS_SYNBIO_GEM_DIR")
            or os.path.join(os.path.expanduser("~"), ".omicverse", "synbio_data"))
    os.makedirs(root, exist_ok=True)
    return root


def _download(url: str, local: str, timeout: float, what: str) -> str:
    if os.path.exists(local) and os.path.getsize(local) > 0:
        return local
    import urllib.request

    tmp = local + ".part"
    try:
        request = urllib.request.Request(
            url, headers={"User-Agent": "omicverse/synbio"})
        with urllib.request.urlopen(request, timeout=timeout) as response, \
                open(tmp, "wb") as handle:
            handle.write(response.read())
        os.replace(tmp, local)
    except Exception as exc:  # pragma: no cover - network
        if os.path.exists(tmp):
            os.remove(tmp)
        raise RuntimeError(
            f"无法下载{what}({exc})。可手动取 {url} 放到 {local}。"
            f"缓存目录可用 OMICOS_SYNBIO_DATA_DIR 环境变量改。"
        ) from exc
    return local


